"""
Draw the SustainML icons listed in icons.json from the Lucide masters.

SmlIcon loads one SVG per colour, images/icons/<name>/<name>_<variant>.svg, so every
variant of every listed icon is written here from the same master: changing an icon or
a colour is an edit to icons.json and a rerun, not a redraw of each file. The icon
section of images.qrc is rewritten to list exactly the generated files.

    generate_icons.py                          write the icons
    generate_icons.py --check                  fail if any icon is out of date
    generate_icons.py --import-lucide <dir>    copy the masters icons.json uses from a
                                               lucide-static npm package
"""

import argparse
import json
import re
import shutil
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONFIG = Path(__file__).resolve().parent / 'icons.json'
LUCIDE_DIR = ROOT / 'thirdparty' / 'lucide'
MASTERS_DIR = LUCIDE_DIR / 'icons'
SRC = ROOT / 'src'
ICONS_DIR = SRC / 'images' / 'icons'
QRC = SRC / 'images.qrc'
SVG_NS = '{http://www.w3.org/2000/svg}'
QRC_BEGIN = '        <!-- icons: generated by tools/icons/generate_icons.py -->'
QRC_END = '        <!-- end of icons -->'


def import_lucide(package_dir, config):
    """Copy the masters config uses, and the licence, from a lucide-static package."""
    package = Path(package_dir)
    MASTERS_DIR.mkdir(parents=True, exist_ok=True)
    shutil.copy(package / 'LICENSE', LUCIDE_DIR / 'LICENSE')
    version = json.loads((package / 'package.json').read_text())['version']
    (LUCIDE_DIR / 'VERSION').write_text(version + '\n')
    for name in sorted({icon['lucide'] for icon in config['icons'].values()}):
        root = ET.parse(package / 'icons' / (name + '.svg')).getroot()
        elements = ['  <{} {}/>'.format(child.tag.replace(SVG_NS, ''), ' '.join(
            '{}="{}"'.format(k, v) for k, v in child.attrib.items())) for child in root]
        (MASTERS_DIR / (name + '.svg')).write_text(
            '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
            'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">\n'
            + '\n'.join(elements) + '\n</svg>\n')


def master_elements(name):
    """The shapes of a master, as (tag, attributes) pairs."""
    root = ET.parse(MASTERS_DIR / (name + '.svg')).getroot()
    return [(child.tag.replace(SVG_NS, ''), dict(child.attrib)) for child in root]


def render(elements, color, fill_shape, stroke_width):
    """An icon in one colour: stroked, or filled too when fill_shape."""
    lines = ['  <{} {}/>'.format(tag, ' '.join('{}="{}"'.format(k, v) for k, v in attributes.items()))
             for tag, attributes in elements]
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" '
            'fill="{}" stroke="{}" stroke-width="{}" stroke-linecap="round" stroke-linejoin="round">\n'
            .format(color if fill_shape else 'none', color, stroke_width)
            + '\n'.join(lines) + '\n</svg>\n')


def qrc_with_icons(qrc, paths):
    """images.qrc text whose generated icon section lists exactly paths."""
    entries = [QRC_BEGIN] + ['        <file>{}</file>'.format(p.relative_to(SRC).as_posix()) for p in paths] + [QRC_END]
    if QRC_BEGIN in qrc:
        return re.sub(re.escape(QRC_BEGIN) + r'.*?' + re.escape(QRC_END), lambda _: '\n'.join(entries), qrc,
                      flags=re.S)
    return qrc.replace('    </qresource>', '\n'.join(entries) + '\n    </qresource>', 1)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='report out of date icons without writing them')
    parser.add_argument('--import-lucide', metavar='DIR', help='lucide-static package to copy the masters from')
    args = parser.parse_args()

    config = json.loads(CONFIG.read_text())
    if args.import_lucide:
        import_lucide(args.import_lucide, config)

    outputs = {}
    for name, icon in sorted(config['icons'].items()):
        elements = master_elements(icon['lucide'])
        for variant, color in sorted(config['variants'].items()):
            path = ICONS_DIR / name / '{}_{}.svg'.format(name, variant)
            outputs[path] = render(elements, color, icon.get('fill', False), config['strokeWidth'])

    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    unlisted = sorted(p for p in ICONS_DIR.rglob('*.svg') if p not in outputs)
    qrc_text = qrc_with_icons(QRC.read_text(), sorted(outputs))
    qrc_stale = qrc_text != QRC.read_text()
    if args.check:
        for path in stale:
            print('out of date:', path.relative_to(ROOT))
        for path in unlisted:
            print('not generated:', path.relative_to(ROOT))
        if qrc_stale:
            print('out of date:', QRC.relative_to(ROOT))
        return 1 if stale or unlisted or qrc_stale else 0

    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(outputs[path])
    for path in unlisted:
        path.unlink()
    for folder in sorted(ICONS_DIR.iterdir()):
        if folder.is_dir() and not any(folder.iterdir()):
            folder.rmdir()
    QRC.write_text(qrc_text)
    print('{} icons written, {} old files removed'.format(len(stale), len(unlisted)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
